"""
POST-HOC follow-up (labeled; NOT pre-registered). Run after the pre-registered main
experiment showed all 8 routed failures were width-4 columns stuck at the partial-XOR
optimum (train acc ~0.74): does doubling capacity (H=16, width-8 columns) remove the
column-trainability failure?  This script regenerates the `posthoc_routed_H16` block of
results.json so the number is auditable code, and compares against the stored block.

Same seeds (700-729), same routing procedure, same thresholds as experiment.py.
"""
import json, time
import numpy as np
import torch
import sys
sys.path.insert(0, "/Users/steven/moral_framework_misgen/undefined/routing-worldview-select")
import experiment as E

# patch the module to H=16 with width-8 columns
E.H = 16
E.UNITS_A = list(range(0, 8))
E.UNITS_B = list(range(8, 16))
E.MASK_KEEP_A = E.unit_mask(E.UNITS_A)
E.MASK_KEEP_B = E.unit_mask(E.UNITS_B)

Xdep, ydep = E.gen_align(4000, 50001, "deploy")
Xhld, yhld = E.gen_align(4000, 60001, "train")

t0 = time.time()
rows = []
for seed in E.SEEDS:
    m, Xtr, ytr = E.train_arm(seed, "routed")
    r = dict(seed=seed,
             full_align=E.accm(m, Xdep, ydep),
             selA_align=E.accm(m, Xdep, ydep, E.MASK_KEEP_A),
             selA_train=E.accm(m, Xhld, yhld, E.MASK_KEEP_A),
             selB_align=E.accm(m, Xdep, ydep, E.MASK_KEEP_B),
             selB_train=E.accm(m, Xhld, yhld, E.MASK_KEEP_B))
    r["success"] = bool(r["selA_align"] > E.ALIGN_HI and r["selA_train"] > E.TRAIN_OK
                        and r["selB_align"] < E.ALIGN_LO and r["selB_train"] > E.TRAIN_OK)
    rows.append(r)

k = sum(r["success"] for r in rows); n = len(rows)
out = dict(label="POST-HOC (regenerated by posthoc_h16.py): not pre-registered; run after seeing "
                 "that all routed failures were width-4 columns stuck at partial-XOR (~0.74 train acc)",
           n=n, successes=k, rate=round(k / n, 4), wilson95=E.wilson(k, n), per_seed=rows,
           runtime_sec=round(time.time() - t0, 1))
print(f"posthoc H=16 routed: {k}/{n} success, wilson95={out['wilson95']} ({out['runtime_sec']}s)")

# compare with the stored block in results.json
path = "/Users/steven/moral_framework_misgen/undefined/routing-worldview-select/results.json"
res = json.load(open(path))
stored = res.get("posthoc_routed_H16")
if stored is not None:
    md = 0.0
    so = {r["seed"]: r for r in stored["per_seed"]}
    for r in rows:
        for kk in ("full_align", "selA_align", "selA_train", "selB_align", "selB_train"):
            md = max(md, abs(r[kk] - so[r["seed"]][kk]))
    print(f"vs stored posthoc block: max|diff| = {md:.6f} "
          f"({'REPRODUCES EXACTLY' if md == 0.0 else 'MISMATCH' if md > 1e-3 else 'within 1e-3'})")
    out["max_abs_diff_vs_originally_stored_block"] = md

json.dump(out, open("/Users/steven/moral_framework_misgen/undefined/routing-worldview-select/posthoc_h16.json", "w"), indent=1)
print("wrote posthoc_h16.json")
